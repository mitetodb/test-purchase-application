#!/bin/sh
# Runs once on first MySQL start. Creates app + pricing databases with least-privilege users.
set -eu
mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS \`${PRICING_DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USERNAME}'@'%' IDENTIFIED BY '${DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${PRICING_DB_USERNAME}'@'%' IDENTIFIED BY '${PRICING_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${DB_NAME}\`.* TO '${DB_USERNAME}'@'%';
GRANT ALL PRIVILEGES ON \`${PRICING_DB_NAME}\`.* TO '${PRICING_DB_USERNAME}'@'%';
FLUSH PRIVILEGES;
SQL
